log = get_logger(__name__)

# ---------------------------------------------------------------------------
# Plan step data
# ---------------------------------------------------------------------------


class StepStatus(StrEnum):
    """Status of a single orchestrator step."""

    PENDING = "pending"
    RUNNING = "running"
    DONE = "done"
    FAILED = "failed"
    SKIPPED = "skipped"
    DENIED = "denied"
    TIMEOUT = "timeout"


@dataclass
class PlanStep:
    """One step in the execution plan visible in the tool-activity panel."""

    tool_name: str
    args: dict[str, Any]
    risk: RiskLevel
    status: StepStatus = StepStatus.PENDING
    result: ToolResult | None = None
    error: str = ""
    step_index: int = 0


@dataclass
class TurnResult:
    """The complete result of one user turn through the orchestrator."""

    reply: str
    status_block: str
    steps: list[PlanStep]
    request_id: str = ""
    total_steps: int = 0
    killed: bool = False


# ---------------------------------------------------------------------------
# Event callback type for real-time UI updates
# ---------------------------------------------------------------------------

StepEventCallback = Callable[[PlanStep], Awaitable[None]] | None


# ---------------------------------------------------------------------------
# Orchestrator
# ---------------------------------------------------------------------------


class Orchestrator:
    """The central plan/act loop.

    Args:
        client: Ollama API client (injected for testing).
        prompt_builder: Prompt builder instance.
        summarizer: Rolling summarizer for conversation history.
        step_callback: Optional async callback invoked when a plan step
            changes state (for WebSocket/UI updates, TASK-025).
    """

    def __init__(
        self,
        client: OllamaClient | None = None,
        prompt_builder: PromptBuilder | None = None,
        summarizer: RollingSummarizer | None = None,
        step_callback: StepEventCallback = None,
    ) -> None:
        self._client = client or OllamaClient(host=cfg.model.ollama_host)
        self._prompt = prompt_builder or PromptBuilder()
        self._summarizer = summarizer or RollingSummarizer()
        self._step_callback = step_callback
        self._registry = get_registry()
        self._model_manager = get_model_manager()
        self._permissions = get_permission_manager()
        self._audit = get_audit_log()
        self._confirmation = default_confirmation_gate
        self._history: list[ChatMessage] = []
        self._turn_count: int = 0

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    async def process_turn(
        self,
        user_input: str,
        categories: set[ToolCategory] | None = None,
        profile_content: str = "",
        memory_content: str = "",
        summary_content: str = "",
    ) -> TurnResult:
        """Process one user turn through the full plan/act loop.

        Args:
            user_input: The user's text input.
            categories: Tool categories to include (None = auto-detect).
            profile_content: User profile text for the prompt.
            memory_content: Recalled memory text for the prompt.
            summary_content: Rolling summary text for the prompt.

        Returns:
            TurnResult with the reply, status block, and step history.
        """
        request_id = uuid.uuid4().hex[:12]
        log.info("turn_start", request_id=request_id, input_len=len(user_input))

        # Reset kill switch for a new request
        if kill_switch.is_killed:
            kill_switch.reset()

        # Add user message to history
        user_msg = ChatMessage(role="user", content=user_input)
        self._history.append(user_msg)

        # Determine tool categories for this request
        if categories is None:
            categories = self._auto_detect_categories(user_input)

        # Retrieve tool schemas
        tool_schemas = self._registry.schemas_for_categories(categories)

        # Build the prompt
        assembled = self._prompt.assemble(
            recent_messages=self._history,
            profile_content=profile_content,
            memory_content=memory_content,
            summary_content=summary_content,
        )

        # Plan/act loop
        steps: list[PlanStep] = []
        step_count = 0
        max_steps = cfg.orchestrator.max_steps
        final_reply = ""
        killed = False

        while step_count < max_steps:
            # Kill switch check
            if kill_switch.is_killed:
                killed = True
                log.warning("killed_between_steps", step=step_count)
                break

            # Model call
            model_name = self._model_manager.current_chat_model
            response = await self._call_model(
                model_name, assembled, tool_schemas if tool_schemas else None
            )

            # Text-only response — we're done
            if not response.tool_calls:
                final_reply = response.content
                break

            # Process each tool call
            step_results: list[ChatMessage] = []
            for tc in response.tool_calls:
                step_count += 1
                if step_count > max_steps:
                    log.warning("max_steps_reached", max=max_steps)
                    final_reply = (
                        response.content or ""
                    ) + f"\n\n[Orchestrator] Step limit ({max_steps}) reached. Remaining actions were not executed."
                    break

                plan_step = PlanStep(
                    tool_name=tc.name,
                    args=tc.arguments,
                    risk=RiskLevel.SAFE,  # will be classified below
                    step_index=step_count,
                )
                steps.append(plan_step)

                # Execute the tool call through the safety pipeline
                result = await self._execute_tool_call(
                    tc, request_id, plan_step
                )
                plan_step.result = result

                # Emit step event for UI
                await self._emit_step(plan_step)

                # Append tool result as a tool message for context
                tool_msg = ChatMessage(
                    role="tool",
                    content=result.output if result.status == "ok" else result.error,
                    name=tc.name,
                )
                step_results.append(tool_msg)

            if step_count > max_steps or killed:
                break

            # Append the assistant's tool-call message
            assistant_msg = ChatMessage(
                role="assistant",
                content=response.content or "",
                tool_calls=response.tool_calls,
            )
            assembled.append(assistant_msg)

            # Append all tool results
            assembled.extend(step_results)

        # Build the status block from code (TASK-023)
        status_block = self._build_status_block(steps)

        # Append the final reply + status block to history
        full_reply = final_reply
        if status_block:
            full_reply = f"{final_reply}\n\n{status_block}" if final_reply else status_block

        self._history.append(ChatMessage(role="assistant", content=full_reply))

        # Increment turn count and maybe summarise
        self._turn_count += 1
        if self._turn_count % cfg.orchestrator.summary_every_n_turns == 0:
            await self._run_summariser()

        result = TurnResult(
            reply=final_reply,
            status_block=status_block,
            steps=steps,
            request_id=request_id,
            total_steps=step_count,
            killed=killed,
        )

        log.info(
            "turn_complete",
            request_id=request_id,
            steps=step_count,
            killed=killed,
            reply_len=len(final_reply),
        )
        return result

    @property
    def history(self) -> list[ChatMessage]:
        """The current conversation history."""
        return list(self._history)

    def clear_history(self) -> None:
        """Clear conversation history and reset turn count."""
        self._history.clear()
        self._turn_count = 0

    # ------------------------------------------------------------------
    # Model call with repair logic
    # ------------------------------------------------------------------

    async def _call_model(
        self,
        model: str,
        messages: list[ChatMessage],
        tools: list[dict] | None,
    ) -> ChatResponse:
        """Call the model, handling errors and fallback to backup."""
        try:
            return await self._client.chat(
                model=model,
                messages=messages,
                tools=tools,
                think=cfg.model.think,
                temperature=cfg.model.temperature,
                top_p=cfg.model.top_p,
                num_ctx=cfg.model.num_ctx,
                num_predict=cfg.model.num_predict,
                keep_alive=cfg.model.keep_alive,
            )
        except Exception as exc:
            log.error("model_call_failed", model=model, error=str(exc))
            # Try the backup model once
            backup = self._model_manager.backup_model
            if model != backup:
                log.info("falling_back_to_backup", model=backup)
                self._model_manager.switch_to_backup()
                return await self._client.chat(
                    model=backup,
                    messages=messages,
                    tools=tools,
                    think=False,
                    temperature=cfg.model.temperature,
                    top_p=cfg.model.top_p,
                    num_ctx=cfg.model.num_ctx,
                    num_predict=cfg.model.num_predict,
                    keep_alive=cfg.model.keep_alive,
                )
            raise

    # ------------------------------------------------------------------
    # Tool execution pipeline
    # ------------------------------------------------------------------

    async def _execute_tool_call(
        self,
        tc: ToolCall,
        request_id: str,
        plan_step: PlanStep,
    ) -> ToolResult:
        """Execute a single tool call through the full safety pipeline.

        Pipeline (ARCHITECTURE section 8):
          1. Lookup tool in registry
          2. Validate arguments against schema (basic presence check)
          3. Classify risk (base + argument escalation)
          4. Permission check (allow/ask/deny)
          5. Confirmation for MEDIUM+ (yes/no or typed phrase)
          6. Execute with timeout
          7. Write audit entry
        """
        plan_step.status = StepStatus.RUNNING
        await self._emit_step(plan_step)

        # 1. Look up the tool
        tool = self._registry.get(tc.name)
        if tool is None:
            plan_step.status = StepStatus.FAILED
            plan_step.error = f"Unknown tool: {tc.name}"
            return ToolResult.error_result(plan_step.error)

        # 2. Argument validation (basic — missing required fields)
        validation_error = self._validate_args(tool, tc.arguments)
        if validation_error:
            # Send one repair message back to the model (ARCHITECTURE section 4)
            plan_step.status = StepStatus.FAILED
            plan_step.error = validation_error
            return ToolResult.error_result(
                f"Invalid arguments for {tc.name}: {validation_error}"
            )

        # 3. Risk classification
        effective_risk = classify_risk(tool.risk, tc.name, tc.arguments)
        plan_step.risk = effective_risk
        log.debug(
            "risk_classified",
            tool=tc.name,
            base_risk=tool.risk.name,
            effective_risk=effective_risk.name,
        )

        # 4. Permission check
        try:
            action = self._permissions.evaluate(tool.category, effective_risk)
        except PermissionDenied as pd:
            plan_step.status = StepStatus.DENIED
            plan_step.error = str(pd)
            self._audit.log_approval(
                tool=tc.name,
                args_masked=self._mask_args(tc.arguments),
                decision="denied",
                risk=effective_risk.name,
                request_id=request_id,
            )
            return ToolResult.denied(str(pd))

        # 5. Confirmation for MEDIUM+ actions
        if action in (PermissionAction.ASK, PermissionAction.ASK_TYPED):
            # Check for untrusted content taint (TASK-039)
            taint = current_turn_taint
            taint_warning = ""
            if taint.is_tainted and effective_risk >= RiskLevel.MEDIUM:
                taint_warning = (
                    f" [Source: {taint.get_source_warning()}]"
                )

            summary = (
                f"{tc.name}({self._summarize_args(tc.arguments)}){taint_warning}"
            )
            target = tc.arguments.get("path", tc.arguments.get("target", ""))

            confirmed = await self._confirmation.request_confirmation(
                tool_name=tc.name,
                risk=effective_risk,
                summary=summary,
                target=str(target),
                timeout_s=cfg.safety.confirmation_timeout_s,
            )

            self._audit.log_approval(
                tool=tc.name,
                args_masked=self._mask_args(tc.arguments),
                decision="approved" if confirmed else "denied",
                risk=effective_risk.name,
                request_id=request_id,
            )

            if not confirmed:
                plan_step.status = StepStatus.DENIED
                plan_step.error = "User denied the action."
                return ToolResult.denied("User denied the action.")

        # 6. Execute with timeout
        try:
            result = await asyncio.wait_for(
                tool.safe_run(tc.arguments),
                timeout=tool.timeout_s,
            )
        except asyncio.TimeoutError:
            plan_step.status = StepStatus.TIMEOUT
            plan_step.error = f"Tool timed out after {tool.timeout_s}s"
            result = ToolResult.timeout_result(tc.name, tool.timeout_s)
        except Exception as exc:
            plan_step.status = StepStatus.FAILED
            plan_step.error = str(exc)
            result = ToolResult.error_result(
                f"Unexpected error in {tc.name}: {type(exc).__name__}: {exc}"
            )

        # Update step status from result
        if result.status == "ok":
            plan_step.status = StepStatus.DONE
        elif result.status == "denied":
            plan_step.status = StepStatus.DENIED
        elif result.status == "timeout":
            plan_step.status = StepStatus.TIMEOUT
        elif plan_step.status == StepStatus.RUNNING:
            plan_step.status = StepStatus.FAILED
            plan_step.error = result.error

        # 7. Audit entry
        self._audit.log_tool_call(
            tool=tc.name,
            args_masked=self._mask_args(tc.arguments),
            result_status=result.status,
            result_error=result.error,
            duration_ms=result.duration_ms,
            request_id=request_id,
            risk=effective_risk.name,
        )

        log.info(
            "tool_executed",
            tool=tc.name,
            status=result.status,
            duration_ms=result.duration_ms,
            risk=effective_risk.name,
        )

        return result

    # ------------------------------------------------------------------
    # Status block (TASK-023)
    # ------------------------------------------------------------------

    @staticmethod
    def _build_status_block(steps: list[PlanStep]) -> str:
        """Generate a code-produced status block from tool results.

        ARCHITECTURE section 4: the status block is generated by code, not
        the model. The model's own wording can never override it.
        """
        if not steps:
            return ""

        lines = ["---", "**Action Status**"]
        for step in steps:
            if step.result:
                lines.append(step.result.to_status_line(step.tool_name))
            elif step.status == StepStatus.DENIED:
                lines.append(f"{step.tool_name}: DENIED - {step.error}")
            elif step.status == StepStatus.SKIPPED:
                lines.append(f"{step.tool_name}: SKIPPED")
            elif step.status == StepStatus.TIMEOUT:
                lines.append(f"{step.tool_name}: TIMEOUT - {step.error}")
            else:
                lines.append(
                    f"{step.tool_name}: FAILED - {step.error or 'Unknown error'}"
                )
        lines.append("---")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Category auto-detection (TASK-024)
    # ------------------------------------------------------------------

    @staticmethod
    def _auto_detect_categories(user_input: str) -> set[ToolCategory]:
        """Heuristic to select relevant tool categories for this request.

        ARCHITECTURE section 6.4: tool schemas are filtered per request by
        category. This saves tokens. Chat-only questions get no file/browser
        tools. The model can always request tools by name via find_tools.

        Returns:
            Set of ToolCategory values to include in this request.
        """
        text = user_input.lower()
        cats: set[ToolCategory] = {ToolCategory.CORE}

        # File operations
        file_keywords = [
            "file", "folder", "directory", "copy", "move", "rename",
            "delete", "create", "write", "read", "search", "find file",
        ]
        if any(k in text for k in file_keywords):
            cats.add(ToolCategory.FILES)

        # System and app control
        system_keywords = [
            "open", "launch", "start", "close", "minimize", "maximize",
            "app", "application", "window", "process", "kill process",
            "whatsapp", "message", "telegram", "automate", "type", "click",
        ]
        if any(k in text for k in system_keywords):
            cats.add(ToolCategory.SYSTEM)
            cats.add(ToolCategory.APP_INTEL)

        # Browser
        browser_keywords = [
            "browse", "web", "search", "google", "url", "website",
            "page", "click", "navigate",
        ]
        if any(k in text for k in browser_keywords):
            cats.add(ToolCategory.BROWSER)

        # Hardware
        hw_keywords = [
            "volume", "brightness", "mute", "unmute", "lock", "sleep",
            "shutdown", "restart", "battery", "cpu", "ram", "gpu", "disk",
        ]
        if any(k in text for k in hw_keywords):
            cats.add(ToolCategory.HARDWARE)

        # Vision
        vision_keywords = [
            "screenshot", "screen", "capture", "camera", "see", "look",
            "what's on", "what is on", "show me", "ocr",
        ]
        if any(k in text for k in vision_keywords):
            cats.add(ToolCategory.VISION)

        # Office
        office_keywords = [
            "excel", "spreadsheet", "word", "document", "powerpoint",
            "presentation", "pdf",
        ]
        if any(k in text for k in office_keywords):
            cats.add(ToolCategory.OFFICE)

        # Shell / code
        shell_keywords = [
            "run command", "terminal", "powershell", "cmd", "execute",
            "script", "code", "python",
        ]
        if any(k in text for k in shell_keywords):
            cats.add(ToolCategory.SHELL)
            cats.add(ToolCategory.CODING)

        # Reminders and notes
        if any(k in text for k in ["remind", "timer", "alarm", "schedule"]):
            cats.add(ToolCategory.REMINDERS)
        if any(k in text for k in ["note", "remember", "save note"]):
            cats.add(ToolCategory.NOTES)

        # Cloud (only if explicitly mentioned)
        if any(k in text for k in ["gemini", "cloud", "generate image"]):
            cats.add(ToolCategory.CLOUD)

        # UI control
        if any(k in text for k in ["click", "type", "automate", "ui"]):
            cats.add(ToolCategory.UI_CONTROL)

        return cats

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _validate_args(tool: BaseTool, args: dict) -> str | None:
        """Basic argument validation against the tool's JSON schema.

        Returns an error string if validation fails, or None if OK.
        """
        schema = tool.parameters
        required = schema.get("required", [])
        properties = schema.get("properties", {})

        missing = [r for r in required if r not in args]
        if missing:
            return f"Missing required argument(s): {', '.join(missing)}"

        # Check for unexpected arguments
        if properties:
            unexpected = [k for k in args if k not in properties]
            if unexpected:
                return f"Unexpected argument(s): {', '.join(unexpected)}"

        return None

    @staticmethod
    def _mask_args(args: dict[str, Any]) -> dict[str, Any]:
        """Mask sensitive values in tool arguments for audit logging."""
        sensitive_keys = {
            "password", "secret", "token", "key", "api_key",
            "credential", "auth", "cookie",
        }
        masked: dict[str, Any] = {}
        for k, v in args.items():
            if any(s in k.lower() for s in sensitive_keys):
                masked[k] = "[REDACTED]"
            elif isinstance(v, str) and len(v) > 500:
                masked[k] = v[:200] + "...[truncated]"
            else:
                masked[k] = v
        return masked

    @staticmethod
    def _summarize_args(args: dict[str, Any]) -> str:
        """Create a short summary of args for the confirmation prompt."""
        if not args:
            return ""
        parts = []
        for k, v in args.items():
            sv = str(v)
            if len(sv) > 60:
                sv = sv[:57] + "..."
            parts.append(f"{k}={sv}")
        return ", ".join(parts[:4])  # At most 4 args in summary

    async def _emit_step(self, step: PlanStep) -> None:
        """Notify the UI about a step state change."""
        if self._step_callback:
            try:
                await self._step_callback(step)
            except Exception as exc:
                log.warning("step_callback_error", error=str(exc))

    async def _run_summariser(self) -> None:
        """Trigger rolling summarisation on the conversation history."""
        try:
            plain_turns = [
                {"role": m.role, "content": m.content or ""}
                for m in self._history
            ]
            summary = await asyncio.to_thread(
                self._summarizer.maybe_summarize, plain_turns
            )
            if summary:
                log.info("conversation_summarised", summary_len=len(summary))
        except Exception as exc:
            log.warning("summariser_error", error=str(exc))
