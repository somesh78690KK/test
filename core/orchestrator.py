"""T.A.R.O. - Orchestrator (plan/act loop).

ARCHITECTURE reference: sections 4, 5.
TASKS: TASK-022, TASK-023, TASK-024, TASK-025.

The orchestrator is the single reasoning loop. It:
1. Builds the prompt (system + profile + memory + summary + recent turns + tools).
2. Calls the model (non-streaming when tools are available, streaming for
   text-only replies).
3. Processes tool calls: validate → risk gate → confirm → execute → audit.
4. Loops back to the model with tool results (max 12 steps per request).
5. Generates a status block from code (model text cannot override it).
6. Stores the turn and triggers summarisation every N turns.

Key invariants enforced in code, not only in the prompt:
- Status block is always generated by code from ToolResults.
- Max steps hard-capped at ``cfg.orchestrator.max_steps``.
- Malformed tool calls get one repair attempt; a second failure ends the step.
- Kill switch checked between every step.
"""

